"""
Intramolecular energies (Intramolecular.jl) against GROMACS: OPLS-AA flexible methanol, seven conformations
evaluated with `gmx mdrun -rerun` (test/data/opls_methanol_intra_reference.txt, generated by
gromacs_fe/intra_ref on 2026-10-12). Tolerances: GROMACS mixed precision prints 6–7 significant figures and
the .gro coordinates carry 0.001 nm, which both sides share exactly, so the terms must agree to 1e-5 relative
(1e-3 kJ/mol absolute for terms near zero). DESIGN.md §7.5, step T7.0.
"""

using Test
using MolSim
const MCm = MolSim.MC

@testset "Intramolecular energies vs GROMACS: OPLS-AA flexible methanol" begin
    bt, types, q, σ_t, ϵ_t = MCm.opls_methanol_bonded()
    # the GROMACS topology uses nrexcl = 3 and explicit 1-4 pairs: H–C–O–H only
    @test length(bt.bonds) == 5 && length(bt.angles) == 7 && length(bt.dihedrals) == 3
    @test sort(bt.pairs14) == [(2, 6), (3, 6), (4, 6)] && isempty(bt.nonbonded)
    σ_mix = [sqrt(a * b) for a in σ_t, b in σ_t]; ϵ_mix = [sqrt(a * b) for a in ϵ_t, b in ϵ_t]
    n = 0
    for line in eachline(joinpath(@__DIR__, "data", "opls_methanol_intra_reference.txt"))
        startswith(line, "#") && continue
        v = parse.(Float64, split(line))
        X = reshape(v[1:18], 3, 6)
        bond_g, angle_g, rb_g, lj14_g, qq14_g, ljsr_g, qqsr_g, pot_g = v[19:26]
        eb, ea, ed = MCm.bonded_energy(bt, X)
        lj14, qq14, lj, qq = MCm.intra_nonbonded_energy(bt, X, types, q, σ_mix, ϵ_mix, MCm.KE_KJMOL_NM)
        close(a, b) = isapprox(a, b; rtol=1e-5, atol=1e-3)
        @test close(eb, bond_g)
        @test close(ea, angle_g)
        @test close(ed, rb_g)
        @test close(lj14, lj14_g)
        @test close(qq14, qq14_g)
        @test lj == 0.0 && qq == 0.0 && ljsr_g == 0.0                    # every pair is excluded or 1-4
        # GROMACS's Coulomb (SR) holds only the reaction-field exclusion correction of the cut-off scheme
        # (not part of the force field); the bonded + 1-4 sum must equal Potential − Coulomb (SR)
        @test close(eb + ea + ed + lj14 + qq14, pot_g - qqsr_g)
        n += 1
    end
    @test n == 7
    # geometry helpers
    X = zeros(3, 4); X[:, 1] .= (1, 0, 0); X[:, 2] .= (0, 0, 0); X[:, 3] .= (0, 1, 0); X[:, 4] .= (0, 1, 1)
    @test MCm.bond_angle(X, 1, 2, 3) ≈ π / 2
    @test abs(MCm.dihedral_angle(X, 1, 2, 3, 4)) ≈ π / 2
    X[:, 4] .= (1, 1, 0)                                                  # cis
    @test MCm.dihedral_angle(X, 1, 2, 3, 4) ≈ 0.0 atol=1e-12
    X[:, 4] .= (-1, 1, 0)                                                 # trans
    @test abs(MCm.dihedral_angle(X, 1, 2, 3, 4)) ≈ π
    # exclusion bookkeeping on a 5-site chain with nrexcl = 3: one 1-4 pair per 3-bond separation, one 1-5
    chain = MCm.BondedTerms(5; bonds=[MCm.HarmonicBond(i, i + 1, 1.0, 1.0) for i in 1:4])
    @test chain.pairs14 == [(1, 4), (2, 5)] && chain.nonbonded == [(1, 5)]
end
